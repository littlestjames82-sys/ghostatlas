@requires_core
def test_cli_brief_and_json_out_create_parent_dirs(tmp_path: Path):
    project = tmp_path / "proj"
    project.mkdir()
    (project / "main.py").write_text(
        '"""Entry."""\nif __name__ == "__main__":\n    print(1)\n')
    result = run_atlas(
        ["build", str(project), "-o", str(tmp_path / "out" / "atlas.html"),
         "--brief", str(tmp_path / "deep" / "nested" / "ATLAS.md"),
         "--json-out", str(tmp_path / "deep2" / "data.json")],
        cwd=tmp_path)
    assert result.returncode == 0, result.stderr
    assert (tmp_path / "deep" / "nested" / "ATLAS.md").is_file()
    assert (tmp_path / "deep2" / "data.json").is_file()


@requires_core
def test_cli_missing_project_error_has_single_prefix(tmp_path: Path):
    result = run_atlas(["build", str(tmp_path / "missing")], cwd=tmp_path)
    assert result.returncode == 2
    assert "ghostatlas: not a directory" in result.stderr
    assert "ghostatlas: ghostatlas:" not in result.stderr


