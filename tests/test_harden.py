# Rendering: dead candidates with present-but-None reason/tokens
# ---------------------------------------------------------------------------

def test_dead_zone_none_reason_does_not_crash_render():
    from ghostatlas.brief import build_brief
    from ghostatlas.reading import dead_zones
    from ghostatlas.render import build_html

    data = AtlasData(root="/x", title="t", run_stamp="s", engine="fallback")
    data.files = [{"path": "a.py", "tokens": 10, "language": "python",
                   "importer_count": 0}]
    data.dead_candidates = [{"path": "a.py", "reason": None, "tokens": None}]
    zones = dead_zones(data)
    assert zones["dead_files"][0]["reason"] == ""
    assert zones["dead_files"][0]["tokens"] == 10
    build_html(data)   # used to raise AttributeError via html.escape(None)
    build_brief(data)
