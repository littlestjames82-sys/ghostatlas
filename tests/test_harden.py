# Hidden paths: removed from EVERY surface, packages stay consistent
# ---------------------------------------------------------------------------

@pytest.mark.skipif(not shutil.which("git"), reason="git not available")
def test_hidden_paths_removed_from_every_surface(tmp_path: Path):
    root = tmp_path / "proj"
    root.mkdir()
    (root / "main.py").write_text(
        '"""Entry."""\nimport util\nif __name__ == "__main__":\n'
        "    print(util.x)\n")
    (root / "util.py").write_text('"""Util."""\nx = 1\n')
    content = '"""Dup module with long content."""\nVALUE = "' + "B" * 80 + '"\n'
    (root / "vis_a.py").write_text(content)
    (root / "vis_b.py").write_text(content)
    (root / "vault.py").write_text(f'"""Vault."""\nTOKEN = "{PLANTED_SECRET}"\n')
    secret = root / "secret"
    secret.mkdir()
    (secret / "hidden.py").write_text(content)
    (secret / "vault2.py").write_text(
        f'"""Hidden vault."""\nTOKEN = "{PLANTED_SECRET}"\n')
    (root / ".ghostslice.json").write_text(
        json.dumps({"atlas": {"hidden_paths": ["secret"]}}))
    for args in (["git", "init", "-q"], ["git", "add", "-A"],
                 ["git", "-c", "user.email=t@t", "-c", "user.name=t",
                  "commit", "-qm", "init"]):
        subprocess.run(args, cwd=root, capture_output=True, check=True)

    data = build_atlas_data(root)
    assert all(not f["path"].startswith("secret/") for f in data.files)
    # Packages used to keep pre-filter counts and disagree with totals.
    assert sum(p["files"] for p in data.packages) == len(data.files)
    assert sum(p["tokens"] for p in data.packages) == data.total_tokens
    # Duplicate cluster keeps only its visible members.
    for group in data.duplicates.get("exact", []):
        assert sorted(group["files"]) == ["vis_a.py", "vis_b.py"]
    # Secrets summary counts/types only for visible files.
    assert data.secrets_summary["count"] == 1
    assert data.secrets_summary["by_file"] == {"vault.py": 1}
    # No surface (incl. lint message text and git activity) names one.
    assert "secret/" not in json.dumps(data.to_dict())
    assert not any("secret/" in k for k in (data.git.get("per_file") or {}))

    from ghostatlas.brief import build_brief
    from ghostatlas.render import build_html
    assert "secret/" not in build_brief(data)
    assert "secret/" not in build_html(data)


