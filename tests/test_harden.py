# ---------------------------------------------------------------------------
# Fallback engine: .gitignore negation
# ---------------------------------------------------------------------------

def test_gitignore_negation_reincludes_file(tmp_path: Path):
    (tmp_path / ".gitignore").write_text("*.log\n!important.log\n")
    (tmp_path / "a.log").write_text("ordinary log content " * 5)
    (tmp_path / "important.log").write_text("important log content " * 5)
    (tmp_path / "main.py").write_text("x = 1\n")
    paths = {f.path for f in engine.fallback_scan(tmp_path).files}
    assert "a.log" not in paths
    assert "important.log" in paths  # was dropped: "!" patterns had no effect


def test_fallback_line_count_trailing_newline(tmp_path: Path):
    (tmp_path / "x.py").write_text("a\nb\n")
    (tmp_path / "y.py").write_text("a\nb")
    files = {f.path: f for f in engine.fallback_scan(tmp_path).files}
    assert files["x.py"].lines == 2  # was 3
    assert files["y.py"].lines == 2


def test_generated_marker_do_not_edit_alone():
    # GhostSlice's detect treats "do not edit" alone as a generated
    # signal; the fallback's and/or precedence silently required more.
    assert engine._looks_generated("Do not edit this file.\ncode\n") is True
    assert engine._looks_generated("Just an ordinary header.\ncode\n") is False


# ---------------------------------------------------------------------------
# Fallback graph: relative `from . import x` and TS explicit extensions
# ---------------------------------------------------------------------------

def test_fallback_graph_relative_from_import(tmp_path: Path):
    pkg = tmp_path / "pkg"
    pkg.mkdir()
    (pkg / "__init__.py").write_text("")
    (pkg / "helper.py").write_text("x = 1\n")
    (pkg / "mod.py").write_text("from . import helper\n")
    (pkg / "mod2.py").write_text("from . import re_exported_name\n")
    (tmp_path / "top.py").write_text("y = 2\n")
    (pkg / "mod3.py").write_text("from .. import top\n")
    graph = engine.fallback_graph(engine.fallback_scan(tmp_path))
    assert graph["pkg/mod.py"]["imports"] == ["pkg/helper.py"]
    # A name that is not a module resolves to the package __init__.
    assert graph["pkg/mod2.py"]["imports"] == ["pkg/__init__.py"]
    assert graph["pkg/mod3.py"]["imports"] == ["top.py"]


def test_fallback_graph_ts_explicit_extensions(tmp_path: Path):
    (tmp_path / "util.ts").write_text("export const u = 1;\n")
    (tmp_path / "data.json").write_text("{}")
    (tmp_path / "a.ts").write_text(
        "import {u} from './util.js';\nimport data from './data.json';\n")
    graph = engine.fallback_graph(engine.fallback_scan(tmp_path))
    assert sorted(graph["a.ts"]["imports"]) == ["data.json", "util.ts"]
    assert graph["a.ts"]["external"] == []


