# Dependency surface: go.mod blocks, requirements option/URL lines
# ---------------------------------------------------------------------------

def test_dependency_surface_go_block_and_requirements_options(tmp_path: Path):
    (tmp_path / "go.mod").write_text(
        "module example.com/x\n\ngo 1.21\n\nrequire (\n"
        " github.com/foo/bar v1.2.3\n"
        " github.com/baz/qux v0.1.0 // indirect\n)\n\n"
        "require example.com/single v1.0.0\n")
    (tmp_path / "requirements.txt").write_text(
        "-r base.txt\n--extra-index-url https://example.com/simple\n"
        "https://example.com/pkg-1.0.whl\nrequests==2.0\n")

    class F:
        def __init__(self, p):
            self.path = p
            self.abspath = str(tmp_path / p)

    deps = dependency_surface(tmp_path, [F("go.mod"), F("requirements.txt")])
    assert "github.com/foo/bar" in deps  # require ( ... ) block was missed
    assert "github.com/baz/qux" in deps
    assert "example.com/single" in deps
    assert "requests" in deps
    assert "-r" not in deps and "--extra-index-url" not in deps
    assert not any("://" in d for d in deps)


